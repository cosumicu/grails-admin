-- Apply through the host application's migration tool when dbCreate is disabled.
-- Compatible with H2 and PostgreSQL; adapt identity syntax for other databases.
CREATE TABLE grails_admin_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL,
    slot VARCHAR(255) NOT NULL UNIQUE,
    username VARCHAR(100) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    session_version VARCHAR(36) NOT NULL
);
